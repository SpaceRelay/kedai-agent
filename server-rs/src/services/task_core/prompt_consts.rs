pub(crate) const CUSTOM_REFLECT_PROMPT: &str = "你是反思审查员。下面是用户目标与上一版产出。检查:目标要求是否全部满足、有无事实/逻辑错误、是否被截断、有无复述指令或元文本。直接输出审查结论:无问题时输出 PASS 并附一句通过理由;有问题时输出 FAIL 并逐条列出需修复的问题。";

